-- Кэш облачной озвучки (§6, вариант A): mp3 фраз, примеров и cloze-предложений.
-- Отдельные слова сюда не попадают - их играет живая запись OneLook.
--
-- Синтез платный и идёт ОДИН раз на фразу: ключ файла - sha256(текст|голос|
-- скорость), поэтому повтор той же фразы это попадание в кэш, а не новый вызов
-- провайдера. Имя файла целиком определяется содержимым, и коллизия означала бы
-- совпадение хэша, а не перезапись чужого.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('tts', 'tts', true, 5242880, array['audio/mpeg'])
on conflict (id) do nothing;

-- Чтение публичное осознанно. Подписанные URL несовместимы с кэшем service
-- worker: у них query-string с истечением, и CacheFirst заводил бы новую запись
-- на каждое воспроизведение - кэш перестал бы работать, а вместе с ним и вся
-- экономия на символах провайдера.
--
-- Утечки данных пользователя тут нет: в бакете лежит озвучка английских фраз
-- из колод, имя файла - хэш, перебором чужой контент не достать.
create policy tts_public_read on storage.objects
  for select using (bucket_id = 'tts');

