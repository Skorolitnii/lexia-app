-- Регион живой озвучки (§6): OneLook отдаёт американскую и британскую запись
-- раздельно, а ссылка строится из слова в момент воспроизведения - значит
-- выбор хранится в настройках, а не в заметке. Тем же значением выбирается
-- акцент синтеза, чтобы слово и его TTS-фолбэк звучали одинаково.
alter table settings
  add column audio_region text not null default 'us'
    check (audio_region in ('us', 'uk'));
