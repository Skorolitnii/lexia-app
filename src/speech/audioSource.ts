import { clozePlainText } from '@/study/cloze'
import type { Direction, NoteRow } from '@/types'

/**
 * Что и чем озвучивать (§6). Источник ОДИН - облачный синтез Azure: и слова, и
 * фразы, и примеры, и cloze-предложения. Локальный синтез устройства остаётся
 * последним рубежом на случай, когда облако недоступно (офлайн, исчерпанная
 * квота, выключенное качество «На устройстве»).
 *
 * Раньше отдельное слово играло живой записью из OneLook, а облако было
 * фолбэком. От этого отказались: у OneLook запись есть далеко не у всех слов,
 * URL - недокументированный внутренний путь сайта, а голоса Azure ровно того
 * же качества на всём материале, а не только на словарных словах. Один
 * источник заодно снимает разнобой, когда слово и его же пример звучали
 * разными голосами.
 */
export interface SpeakSource {
  /**
   * Готовый адрес mp3, если он известен заранее. Сейчас всегда `null`: адрес
   * облачного файла считается внутри `useSpeech` из текста, голоса и скорости.
   * Поле оставлено, потому что заметка может нести собственный `audio_url`
   * из импортированного чужого JSON (§5, loseless).
   */
  url: string | null
  /** Текст для синтеза - и облачного, и локального. */
  text: string
  /**
   * Отдать текст облаку. Практически всегда `true`: облако - основной источник.
   * `false` означало бы «озвучить только локально».
   */
  cloud?: boolean
}

/**
 * Источник озвучки главного текста карточки.
 *
 * У `cloze` озвучивается предложение целиком (`clozePlainText`), а не слово:
 * `front` у cloze - предложение с разметкой `{{...}}`, и произносить её нельзя.
 * У `forward`/`reverse` озвучивается EN-сторона, то есть `front` в обоих
 * случаях: на обороте reverse появляется то же самое английское слово.
 */
export function cardSpeakSource(note: NoteRow, direction: Direction): SpeakSource {
  const text = direction === 'cloze' ? clozePlainText(note.front) : note.front
  return { url: null, text, cloud: true }
}
